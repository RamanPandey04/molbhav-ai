import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const page = readFileSync(root + "src/pages/home.tsx", "utf8");
const html = readFileSync(root + "index.html", "utf8");

test("original copy is preserved", () => {
  for (const s of ["To get started, edit the", "page.tsx", "Looking for a starting point or more instructions? Head over to", "Templates", "Learning", "center.", "Deploy Now", "Documentation", "Next.js logo", "Vercel logomark"]) {
    assert.ok(page.includes(s), s);
  }
});

test("link destinations are preserved", () => {
  for (const h of [
    "https://vercel.com/templates?framework=next.js&utm_source=create-next-app&utm_medium=appdir-template-tw&utm_campaign=create-next-app",
    "https://nextjs.org/learn?utm_source=create-next-app&utm_medium=appdir-template-tw&utm_campaign=create-next-app",
    "https://vercel.com/new?utm_source=create-next-app&utm_medium=appdir-template-tw&utm_campaign=create-next-app",
    "https://nextjs.org/docs?utm_source=create-next-app&utm_medium=appdir-template-tw&utm_campaign=create-next-app",
  ]) assert.ok(page.includes('href="' + h + '"'), h);
});

test("assets exist and no next/* imports remain", () => {
  for (const a of ["next.svg", "vercel.svg", "favicon.ico"]) assert.ok(existsSync(root + "public/" + a), a);
  assert.ok(page.includes('asset("/next.svg")') && page.includes('asset("/vercel.svg")'));
  assert.ok(!/from ["']next\//.test(page));
});

test("metadata preserved", () => {
  assert.ok(html.includes("<title>Create Next App</title>"));
  assert.ok(html.includes('content="Generated by create next app"'));
});
